-- 장기보험 회차별 지급률 마스터 — 운영 DB와 체험판 DB 모두 SQL Editor에서 한 번 통째로 실행한다.
--
-- 보험사 장기 수수료 규정의 '회차별 지급률'을 (보험사, 상품유형, 실적구간, 회차) 단위로 저장한다.
-- 모든 지급률은 월납환산 수정보험료(수정P) 대비 % 이다. 예상 수수료 = 월납환산 수정P × rate_pct / 100.
-- DB손보 원표는 영수P 기준(초회 수정P 240%)이라 ÷2.4 로 환산해서 넣었다.
-- 규정이 바뀌면 새 effective_month 로 다시 넣는다(지난 기준은 남겨 둠). 다시 실행해도 중복되지 않는다.
create table if not exists long_commission_rates (
  insurer text not null,                 -- contracts.company 와 같은 표기 (메리츠화재, 삼성화재, DB손보, KB손보 …)
  product_type text not null,            -- 보험사 지급유형 (M1, S10, D1, K3 …)
  band text not null default '',         -- 실적구간 (8천↑ 등), 구간이 없는 유형은 ''
  band_order int not null default 1,     -- 구간 표시 순서 (높은 구간이 1)
  installment int not null check (installment between 1 and 120), -- 회차
  rate_pct numeric not null,             -- 수정P 대비 지급률(%)
  effective_month text not null,         -- 적용 시작월 'YYYY-MM'
  updated_by uuid references profiles(id),
  updated_at timestamptz default now(),
  primary key (insurer, product_type, band, installment, effective_month)
);

-- 로그인한 회원은 모두 조회 (FC는 화면에서 본인 장기 지급률을 곱해 본다). 등록·수정은 본사 소속만.
alter table long_commission_rates enable row level security;
drop policy if exists "long_commission_rates_select_admin" on long_commission_rates;
drop policy if exists "long_commission_rates_select_member" on long_commission_rates;
create policy "long_commission_rates_select_member" on long_commission_rates
  for select using (my_role() is not null);
drop policy if exists "long_commission_rates_write_hq" on long_commission_rates;
create policy "long_commission_rates_write_hq" on long_commission_rates
  for all using (my_org() = 'hq') with check (my_org() = 'hq');

