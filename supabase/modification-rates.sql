-- 보험사가 공지하는 상품별 수정률(보험료 → 수정보험료 환산 비율, %)을 상품·세부구분·납기 단위로 저장한다.
-- 장기 지급률표(long_commission_rates)는 수정P 대비 %이므로, 영수P × 수정률 = 수정P 를 구할 때 참고한다.
-- 보험사 공지 원문상 '단순 참고용이며 수수료 지급 근거가 아님'. 다시 실행해도 중복되지 않는다.
create table if not exists modification_rates (
  insurer text not null,               -- contracts.company 와 같은 표기
  line text not null default '',       -- 人보험 / 物보험 / 저축성
  category text not null default '',   -- 건강, 간편, 자녀, 운전자 …
  product text not null,               -- 상품명 (공지 표기 그대로)
  segment text not null default '',    -- 담보군·갱신구분·개인/단체 등 세부구분
  term text not null default '',       -- 납입기간/보험기간 (예: 20년납↑, 최초)
  rate_pct numeric not null,           -- 수정률(%)
  note text not null default '',
  sort_order int not null default 0,   -- 표시 순서 (상품·세부구분)
  term_order int not null default 0,   -- 상품 안에서 납기 열 순서
  effective_month text not null,       -- 공지 기준월 'YYYY-MM'
  updated_at timestamptz default now(),
  primary key (insurer, product, segment, term, effective_month)
);

-- 장기 지급률표와 같은 범위: 로그인 회원 모두 조회, 본사 소속만 등록·수정
alter table modification_rates enable row level security;
drop policy if exists "modification_rates_select_admin" on modification_rates;
drop policy if exists "modification_rates_select_member" on modification_rates;
create policy "modification_rates_select_member" on modification_rates
  for select using (my_role() is not null);
drop policy if exists "modification_rates_write_hq" on modification_rates;
create policy "modification_rates_write_hq" on modification_rates
  for all using (my_org() = 'hq') with check (my_org() = 'hq');

